"""Convert owner's HEIC/JPEG/PNG photographs into orientation-correct web copies.
Originals are read-only. MOV clips are inventoried but not used as still photos.
Run without --publish to produce review contact sheets under /tmp/fei-inspiration-review.
"""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path
from PIL import Image, ImageOps, ImageDraw

parser = argparse.ArgumentParser()
parser.add_argument('--publish', action='store_true')
parser.add_argument('--refresh', action='store_true', help='Regenerate review copies with the system image decoder')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
review = Path('/tmp/fei-inspiration-review')
review.mkdir(exist_ok=True)
records = []
skipped = []
for category in ['animals', 'flowers']:
    folder = Path('/Users/fayechen/Desktop') / ('quick sketch ' + category)
    for source in sorted(folder.iterdir()):
        if source.suffix.lower() not in ['.heic', '.jpg', '.jpeg', '.png']:
            if source.suffix.lower() in ['.mov', '.mp4']:
                skipped.append({'category': category, 'source': source.name, 'reason': 'Video clip; no arbitrary frame used'})
            continue
        identifier = category + '-' + hashlib.sha256(source.name.encode()).hexdigest()[:10]
        output = review / (identifier + '.jpg')
        if args.refresh or not output.exists():
            converted = review / (identifier + '-converted.jpg')
            subprocess.run(['sips', '-s', 'format', 'jpeg', '-Z', '1400', str(source), '--out', str(converted)], check=True, capture_output=True)
            with Image.open(converted) as original:
                photo = ImageOps.exif_transpose(original).convert('RGB')
                if max(channel[1] for channel in photo.getextrema()) == 0:
                    raise RuntimeError('System decoder returned a black image: '+source.name)
                # Re-encode without location, device or date metadata.
                photo.save(output, 'JPEG', quality=82, optimize=True)
            converted.unlink()
        records.append({'id': identifier, 'category': category, 'source': source.name, 'file': output.name})
    entries = [r for r in records if r['category'] == category]
    for offset in range(0, len(entries), 24):
        page = entries[offset:offset+24]
        sheet = Image.new('RGB', (1000, ((len(page)+4)//5)*190), '#f6f0e4')
        draw = ImageDraw.Draw(sheet)
        for i, record in enumerate(page):
            with Image.open(review / record['file']) as original:
                thumb = ImageOps.contain(original, (190, 150))
                x, y = (i % 5)*200, (i // 5)*190
                sheet.paste(thumb, (x+(200-thumb.width)//2, y))
                draw.text((x+6, y+154), record['source'][:27], fill='#20202a')
                draw.text((x+6, y+170), record['id'], fill='#20202a')
        sheet.save(review / (category + '-sheet-' + str(offset//24+1) + '.jpg'))

if args.publish:
    annotations = json.loads((root / 'docs/inspiration-photo-selection.json').read_text())
    target = root / 'assets/inspiration'
    target.mkdir(exist_ok=True)
    published = []
    for record in records:
        label = annotations.get(record['id'])
        if not label:
            skipped.append({**record, 'reason': 'Not selected after visual review'})
            continue
        (target / record['file']).write_bytes((review / record['file']).read_bytes())
        published.append({'id': record['id'], 'category': record['category'], 'title': label, 'url': '../assets/inspiration/'+record['file'], 'alt': 'Photograph: '+label, 'source': 'Owner-provided Quick Sketch '+record['category']+' collection'})
    (root / 'core/inspiration-photos.js').write_text('/* Owner-provided photographs. Generated by scripts/import-inspiration-photos.py. */\nwindow.FEIInspirationPhotos = '+json.dumps(published, ensure_ascii=False, indent=2)+';\n')
    (root / 'docs/inspiration-photo-manifest.json').write_text(json.dumps({'photos': records, 'published': len(published), 'skipped': skipped}, ensure_ascii=False, indent=2)+'\n')
print(json.dumps({'review_photos': len(records), 'video_clips': len([r for r in skipped if r.get('reason', '').startswith('Video')]), 'review_directory': str(review)}))
